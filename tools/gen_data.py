"""Regenerates Data.lua from WoW Forever's game tables on wago.tools.

    python tools/gen_data.py [build]

The lists are spell IDs, so they hold in every client language. The build
defaults to the newest WoW Forever (wowf) build wago.tools knows.
"""
import collections
import csv
import io
import json
import os
import sys
import urllib.request

UA = {"User-Agent": "Mozilla/5.0"}
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "Data.lua")


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA)) as r:
        return r.read().decode("utf-8")


def table(name, build):
    text = fetch(f"https://wago.tools/db2/{name}/csv?build={build}")
    return list(csv.DictReader(io.StringIO(text)))


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else json.loads(fetch("https://wago.tools/api/builds"))["wowf"][0]["version"]
    items = {r["ID"]: r for r in table("Item", build)}
    effects = {r["ID"]: r for r in table("ItemEffect", build)}
    names = {r["ID"]: r["Name_lang"] for r in table("SpellName", build)}
    spell_effects = collections.defaultdict(list)
    for r in table("SpellEffect", build):
        spell_effects[r["SpellID"]].append(r)

    # Every on-use spell of a consumable (item class 0).
    known = set()
    for r in table("ItemXItemEffect", build):
        item, effect = items.get(r["ItemID"]), effects.get(r["ItemEffectID"])
        if item and effect and item["ClassID"] == "0" and effect["TriggerType"] == "0":
            known.add(int(effect["SpellID"]))

    def has(spell, test):
        return any(test(e) for e in spell_effects[str(spell)])

    def aura(e, *ids):
        return e["Effect"] == "6" and e["EffectAura"] in ids

    # A spell is food or drink by name ("Food", "Drink") or by triggering
    # one: WoW Forever's buff food casts "Nutritious Food", which triggers
    # the plain Food spell and adds the buff.
    def kind(spell):
        name = names.get(str(spell))
        if name in ("Food", "Drink", "First Aid"):
            return {name}
        found = set()
        for e in spell_effects[str(spell)]:
            if e["Effect"] == "64" and names.get(e["EffectTriggerSpell"]) in ("Food", "Drink"):
                found.add(names[e["EffectTriggerSpell"]])
        return found

    food = {s for s in known if "Food" in kind(s)}
    drink = {s for s in known if "Drink" in kind(s)}
    firstaid = {s for s in known if "First Aid" in kind(s)}
    eat = food | drink | firstaid
    # Health: instant heal, heal %, periodic heal, % health over time.
    health = {s for s in known - eat if has(s, lambda e: e["Effect"] in ("10", "136") or aura(e, "8", "20"))}
    # Mana: energize or periodic energize with power type 0.
    mana = {s for s in known - eat - health if has(s, lambda e: e["EffectMiscValue_0"] == "0" and (
        e["Effect"] == "30" or aura(e, "24", "21")))}
    # Buff food/drink: anything beyond the plain health/mana regen auras
    # (84/85 regen, 20/21 % over time), e.g. a triggered Well Fed.
    plain = ("84", "85", "20", "21")
    buff = {s for s in food | drink if has(s, lambda e: not aura(e, *plain))}

    def ids(s):
        out, line = [], ""
        for i in sorted(s):
            part = f"{i},"
            if len(line) + len(part) > 76:
                out.append(line)
                line = ""
            line += part
        out.append(line)
        return "\n\t".join(out)

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"""-- Generated by tools/gen_data.py from WoW Forever {build} game data. Do not edit.
-- Spell IDs of consumables' on-use spells, the same in every client language.
local _, ns = ...

local function set(list)
\tlocal t = {{}}
\tfor _, id in ipairs(list) do t[id] = true end
\treturn t
end

ns.DATA_BUILD = "{build}"

-- Every consumable on-use spell this data knows; others are newer and
-- fall back to reading their description.
ns.KNOWN = set({{
\t{ids(known)}
}})

ns.FOOD = set({{
	{ids(food)}
}})

ns.DRINK = set({{
	{ids(drink)}
}})

ns.FIRSTAID = set({{
	{ids(firstaid)}
}})

ns.HEALTH = set({{
\t{ids(health)}
}})

ns.MANA = set({{
\t{ids(mana)}
}})

-- Food and drink that also buff (Well Fed and the like).
ns.BUFF = set({{
\t{ids(buff)}
}})
""")
    print(f"{build}: {len(known)} known, {len(food)} food, {len(drink)} drink, {len(firstaid)} first aid, {len(health)} health, {len(mana)} mana, {len(buff)} buff -> {OUT}")


if __name__ == "__main__":
    main()
